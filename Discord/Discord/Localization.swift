import Foundation
import SwiftUI

enum AppLanguage: String, CaseIterable, Identifiable, Codable {
    case english = "en"
    case spanish = "es"
    case portuguese = "pt"

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .english: return "English"
        case .spanish: return "Español"
        case .portuguese: return "Português"
        }
    }

    var subtitle: String {
        switch self {
        case .english: return "English (United States)"
        case .spanish: return "Español (Latinoamérica)"
        case .portuguese: return "Português (Brasil)"
        }
    }

    var locale: Locale {
        Locale(identifier: rawValue)
    }

    static let storageKey = "discord.language"
}

struct Localizer {
    let language: AppLanguage

    func callAsFunction(_ key: String) -> String {
        L10n.text(key, language)
    }
}

private struct LocalizerKey: EnvironmentKey {
    static let defaultValue = Localizer(language: .english)
}

extension EnvironmentValues {
    var t: Localizer {
        get { self[LocalizerKey.self] }
        set { self[LocalizerKey.self] = newValue }
    }
}

