    static func text(_ key: String, _ language: AppLanguage) -> String {
        switch language {
        case .english: return en[key] ?? key
        case .spanish: return es[key] ?? en[key] ?? key
        case .portuguese: return pt[key] ?? en[key] ?? key
        }
    }

